"""Permutation groups: deterministic Schreier-Sims, orbits, blocks, stabilizers.

References: HBD Sec. 2.1 (Schreier-Sims, Algorithm 1; orbits and blocks,
Sec. 2.1.2 following Sims/Atkinson; Exercise 2.1.1 (a)-(c) for membership,
subgroups of small index and preimages of homomorphisms), Babai Sec. 2.2.

Groups are given by generators (Babai Sec. 3.1).  A ``PermGroup`` lazily builds a
base and strong generating set (BSGS) by the deterministic Schreier-Sims
algorithm.  The base is chosen greedily in a prescribed priority order
(``base_order``); an optional ``forced_prefix`` of points is placed at the top of
the stabilizer chain so that the subgroup fixing all of them pointwise is the
chain level after the prefix (used for pointwise stabilizers, kernels of
homomorphisms via the combined action on Omega + Gamma, and for lifting
permutations of an invariant window back to the group, Babai Obs. 3.1.10).
"""

from __future__ import annotations

from collections import deque
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

from .perm import Perm, identity, inv, is_identity, mul

# generating sets larger than this are pruned to an irredundant subset on construction
PRUNE_THRESHOLD = 6


class _Level:
    __slots__ = ("b", "trans", "trans_inv", "gens", "pending", "points")

    def __init__(self, b: int, n: int):
        self.b = b
        self.trans: Dict[int, Perm] = {b: identity(n)}
        self.trans_inv: Dict[int, Perm] = {b: identity(n)}
        self.gens: List[Perm] = []
        self.pending: deque = deque()  # (point, generator index) Schreier pairs to sift
        self.points: List[int] = [b]  # orbit points in insertion order


class PermGroup:
    """A permutation group on {0,...,n-1} given by generators."""

    def __init__(self, n: int, gens: Iterable[Perm], base_order: Optional[Sequence[int]] = None,
                 forced_prefix: Sequence[int] = (), known_order: Optional[int] = None):
        self.n = n
        seen = set()
        gl: List[Perm] = []
        for g in gens:
            g = tuple(g)
            if len(g) != n:
                raise ValueError("generator of wrong degree")
            if g in seen or is_identity(g):
                continue
            seen.add(g)
            gl.append(g)
        self.gens: List[Perm] = gl
        self.base_order = list(base_order) if base_order is not None else list(range(n))
        self.forced_prefix = list(forced_prefix)
        self.known_order = known_order
        self._levels: Optional[List[_Level]] = None
        self._order: Optional[int] = None
        self._orbits: Optional[List[List[int]]] = None
        # caches used by the String Isomorphism solver (keyed by strings / windows)
        self.aut_cache: Dict = {}
        self.stage_cache: Dict = {}
        self.lifter_cache: Dict = {}
        self.prefix_cache: Dict = {}
        self.agg_cache: Dict = {}
        if len(gl) > PRUNE_THRESHOLD:
            # Large generating sets (all automorphisms found by brute force, unions
            # of cosets, lifted generators plus kernels) are pruned to an
            # irredundant subset right away, before anybody can see ``self.gens``:
            # the incremental Schreier-Sims build below drops every generator
            # that already lies in the group generated by its predecessors.
            self._build(prune=True)

    # ------------------------------------------------------------------ BSGS
    def _build(self, prune: bool = False) -> None:
        if self._levels is not None:
            return
        n = self.n
        levels: List[_Level] = []
        moved_by_gens = set()
        for g in self.gens:
            for i, v in enumerate(g):
                if i != v:
                    moved_by_gens.add(i)
        for b in self.forced_prefix:
            if b in moved_by_gens:
                levels.append(_Level(b, n))
        prefix_set = set(self.forced_prefix)
        rest_order = [b for b in self.base_order if b not in prefix_set]
        base_set = set(self.base_order)
        rest_order.extend(b for b in range(n) if b not in prefix_set and b not in base_set)
        self._levels = levels
        target = self.known_order

        def sift(g: Perm, start: int) -> Tuple[int, Perm]:
            for i in range(start, len(levels)):
                lev = levels[i]
                ui = lev.trans_inv.get(g[lev.b])
                if ui is None:
                    return i, g
                g = mul(g, ui)
            return len(levels), g

        def extend_orbit(lev: _Level, new_gen_index: Optional[int]) -> None:
            # extend the orbit of lev.b under lev.gens; register new Schreier pairs
            gens = lev.gens
            if new_gen_index is not None:
                for pt in list(lev.points):
                    lev.pending.append((pt, new_gen_index))
            queue = deque(lev.points)
            while queue:
                pt = queue.popleft()
                u = lev.trans[pt]
                for gi, s in enumerate(gens):
                    q = s[pt]
                    if q not in lev.trans:
                        us = mul(u, s)
                        lev.trans[q] = us
                        lev.trans_inv[q] = inv(us)
                        lev.points.append(q)
                        queue.append(q)
                        for gj in range(len(gens)):
                            lev.pending.append((q, gj))

        def add_strong_gen(h: Perm, lo: int, hi: int) -> None:
            # h fixes base points of levels < lo ... (h is in G^{(lo)}); add to levels lo..hi inclusive
            if hi == len(levels):
                # new level needed: pick first point in priority order moved by h
                b = None
                for cand in rest_order:
                    if h[cand] != cand:
                        b = cand
                        break
                if b is None:
                    raise RuntimeError("non-identity residue fixing all points")
                levels.append(_Level(b, n))
            for i in range(lo, hi + 1):
                lev = levels[i]
                lev.gens.append(h)
                extend_orbit(lev, len(lev.gens) - 1)

        def current_order() -> int:
            o = 1
            for lev in levels:
                o *= len(lev.trans)
            return o

        def closure() -> bool:
            # process Schreier generators deepest level first; True if the target order was reached
            i = len(levels) - 1
            while i >= 0:
                lev = levels[i]
                if lev.pending:
                    pt, gi = lev.pending.popleft()
                    s = lev.gens[gi]
                    u = lev.trans[pt]
                    q = s[pt]
                    y = mul(mul(u, s), lev.trans_inv[q])
                    if is_identity(y):
                        continue
                    j, h = sift(y, i + 1)
                    if not is_identity(h):
                        add_strong_gen(h, i + 1, j)
                        if target is not None and current_order() == target:
                            for lv in levels:
                                lv.pending.clear()
                            return True
                        i = j if j < len(levels) else len(levels) - 1
                    continue
                i -= 1
            return False

        # incremental Schreier-Sims: generators are added one at a time and the
        # chain is completed after each essential generator, so that redundant
        # generators are recognised by a single sift
        essential: List[Perm] = []
        done = target is not None and current_order() == target
        for g in self.gens:
            if done:
                break
            j, h = sift(g, 0)
            if is_identity(h):
                continue
            essential.append(g)
            add_strong_gen(h, 0, j)
            if target is not None and current_order() == target:
                for lv in levels:
                    lv.pending.clear()
                done = True
                continue
            done = closure()
        self._order = current_order()
        if prune:
            self.gens = essential

    @property
    def levels(self) -> List[_Level]:
        self._build()
        return self._levels  # type: ignore

    def order(self) -> int:
        if self._order is None and self.known_order is not None:
            return self.known_order
        self._build()
        return self._order  # type: ignore

    def is_trivial(self) -> bool:
        return not self.gens

    def base(self) -> List[int]:
        return [lev.b for lev in self.levels]

    def sift(self, g: Perm, start: int = 0) -> Tuple[int, Perm]:
        levels = self.levels
        for i in range(start, len(levels)):
            lev = levels[i]
            ui = lev.trans_inv.get(g[lev.b])
            if ui is None:
                return i, g
            g = mul(g, ui)
        return len(levels), g

    def contains(self, g: Perm) -> bool:
        j, h = self.sift(tuple(g))
        return j == len(self.levels) and is_identity(h)

    def strong_gens(self) -> List[Perm]:
        out: List[Perm] = []
        seen = set()
        for lev in self.levels:
            for g in lev.gens:
                if g not in seen:
                    seen.add(g)
                    out.append(g)
        return out

    # --------------------------------------------------------- stabilizers
    def level_group(self, i: int, known_order: Optional[int] = None) -> "PermGroup":
        """The pointwise stabilizer of the first i base points, as a group."""
        levels = self.levels
        gens = levels[i].gens if i < len(levels) else []
        if known_order is None:
            o = 1
            for lev in levels[i:]:
                o *= len(lev.trans)
            known_order = o
        return PermGroup(self.n, gens, known_order=known_order)

    def prefix_group(self, points: Sequence[int]) -> "PermGroup":
        """This group rebuilt with ``points`` forced to the top of the base (cached)."""
        pts = list(dict.fromkeys(points))
        key = tuple(pts)
        H = self.prefix_cache.get(key)
        if H is None:
            H = PermGroup(self.n, self.gens, forced_prefix=pts, known_order=self.known_order_or_none())
            self.prefix_cache[key] = H
        return H

    def known_order_or_none(self) -> Optional[int]:
        return self._order if self._order is not None else self.known_order

    def pointwise_stabilizer(self, points: Sequence[int]) -> "PermGroup":
        """G_(points) (Babai eq. (5)) via a chain with ``points`` on top."""
        pts = [p for p in dict.fromkeys(points)]
        if not pts:
            return self
        H = self.prefix_group(pts)
        levels = H.levels
        k = 0
        pset = set(pts)
        while k < len(levels) and levels[k].b in pset:
            k += 1
        return H.level_group(k)

    def point_stabilizer(self, p: int) -> "PermGroup":
        return self.pointwise_stabilizer([p])

    # ------------------------------------------------------------- orbits
    def orbits(self) -> List[List[int]]:
        if self._orbits is None:
            n = self.n
            seen = [False] * n
            out = []
            for s in range(n):
                if seen[s]:
                    continue
                orb = [s]
                seen[s] = True
                q = deque([s])
                while q:
                    p = q.popleft()
                    for g in self.gens:
                        v = g[p]
                        if not seen[v]:
                            seen[v] = True
                            orb.append(v)
                            q.append(v)
                out.append(orb)
            self._orbits = out
        return self._orbits

    def orbit(self, s: int) -> List[int]:
        for orb in self.orbits():
            if s in orb:
                return orb
        raise ValueError

    def is_transitive(self) -> bool:
        return len(self.orbits()) == 1

    def orbits_on(self, items: Sequence, act) -> List[List]:
        """Orbits on arbitrary hashable items under ``act(item, g)``."""
        index = {it: i for i, it in enumerate(items)}
        seen = [False] * len(items)
        out = []
        for i, it in enumerate(items):
            if seen[i]:
                continue
            seen[i] = True
            orb = [it]
            q = deque([it])
            while q:
                cur = q.popleft()
                for g in self.gens:
                    nx = act(cur, g)
                    j = index[nx]
                    if not seen[j]:
                        seen[j] = True
                        orb.append(nx)
                        q.append(nx)
            out.append(orb)
        return out

    # -------------------------------------------------------------- blocks
    def minimal_block_system(self) -> List[List[int]]:
        """A minimal system of imprimitivity (maximal blocks) of a transitive group.

        HBD Sec. 2.1.2 (Sims/Atkinson): for a != b, the finest block containing
        a and b is the component of a in the graph with edge-orbit {a,b}^G.  We
        iterate: find any nontrivial block, pass to the induced action on the
        block system, and repeat until the action is primitive.  Returns the
        singleton partition if the group is primitive (or |Omega| <= 1).
        """
        n = self.n
        if not self.is_transitive():
            raise ValueError("block systems require a transitive group")
        blocks = [[i] for i in range(n)]
        if n <= 1:
            return blocks
        gens = self.gens
        while True:
            m = len(blocks)
            if m == 1:
                return blocks
            index = {}
            for bi, blk in enumerate(blocks):
                for p in blk:
                    index[p] = bi
            # induced generators on the block set
            igens = []
            for g in gens:
                igens.append(tuple(index[g[blocks[bi][0]]] for bi in range(m)))
            found = None
            a = 0
            for b in range(1, m):
                part = _atkinson(m, igens, a, b)
                nb = len(set(part))
                if 1 < nb < m:
                    found = part
                    break
                if nb == 1:
                    # a and b lie in no proper block together; try next b
                    continue
            if found is None:
                return blocks
            # merge blocks according to the partition found (coarsening)
            groups: Dict[int, List[int]] = {}
            for bi in range(m):
                groups.setdefault(found[bi], []).extend(blocks[bi])
            blocks = [sorted(v) for v in groups.values()]
            blocks.sort()

    # ------------------------------------------------------------ actions
    def induced_action(self, blocks: Sequence[Sequence[int]]) -> Tuple["PermGroup", List[Perm]]:
        """Action on an invariant partition; returns (group on blocks, images of gens)."""
        index = {}
        for bi, blk in enumerate(blocks):
            for p in blk:
                index[p] = bi
        imgs = []
        for g in self.gens:
            imgs.append(tuple(index[g[blk[0]]] for blk in blocks))
        return PermGroup(len(blocks), imgs), imgs

    def restriction(self, points: Sequence[int]) -> Tuple["PermGroup", List[Perm]]:
        """Restriction G^Delta to an invariant set (Babai Notation 2.2.1)."""
        pts = list(points)
        index = {p: i for i, p in enumerate(pts)}
        imgs = [tuple(index[g[p]] for p in pts) for g in self.gens]
        return PermGroup(len(pts), imgs), imgs

    # ---------------------------------------------------------- enumerate
    def elements(self) -> Iterable[Perm]:
        """All group elements, each exactly once (products of transversals)."""
        levels = self.levels
        n = self.n
        if not levels:
            yield identity(n)
            return

        def rec(i: int, acc: Perm):
            if i < 0:
                yield acc
                return
            for u in levels[i].trans.values():
                yield from rec(i - 1, mul(acc, u))

        # g = u_{k-1} ... u_1 u_0  (apply u_{k-1} first)
        yield from rec(len(levels) - 1, identity(n))

    def coset_reps_prefix(self, k: int) -> Iterable[Perm]:
        """Right coset representatives of the k-th level subgroup G^{(k)} in G.

        G = disjoint union of G^{(k)} * (u_{k-1} ... u_0) over transversal choices.
        """
        levels = self.levels
        n = self.n
        k = min(k, len(levels))

        def rec(i: int, acc: Perm):
            if i < 0:
                yield acc
                return
            for u in levels[i].trans.values():
                yield from rec(i - 1, mul(acc, u))

        yield from rec(k - 1, identity(n))

    # ------------------------------------------------------------ helpers
    def random_free_subgroup_gens(self) -> List[Perm]:
        return list(self.gens)

    def __repr__(self) -> str:
        return f"PermGroup(n={self.n}, gens={len(self.gens)})"


def _atkinson(m: int, gens: List[Perm], a: int, b: int) -> List[int]:
    """Union-find closure of the relation generated by (a ~ b) under the group."""
    parent = list(range(m))

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x: int, y: int) -> bool:
        rx, ry = find(x), find(y)
        if rx == ry:
            return False
        parent[rx] = ry
        return True

    union(a, b)
    queue = [(a, b)]
    while queue:
        x, y = queue.pop()
        for g in gens:
            gx, gy = g[x], g[y]
            if union(gx, gy):
                queue.append((gx, gy))
    return [find(x) for x in range(m)]


# ----------------------------------------------------------------- utilities

def generated_subcoset(n: int, cosets: Sequence[Tuple["PermGroup", Perm]], known_order: Optional[int] = None):
    """Smallest subcoset containing the right cosets H_i sigma_i (Babai Def. 9.0.3).

    If the cosets are the pieces of a single coset (as in Luks reductions), the
    result is that coset: <H_i, sigma_i sigma_1^{-1}> sigma_1.
    """
    cosets = [c for c in cosets if c is not None]
    if not cosets:
        return None
    H1, s1 = cosets[0]
    gens: List[Perm] = []
    s1inv = inv(s1)
    for H, s in cosets:
        gens.extend(H.gens)
        gens.append(mul(s, s1inv))
    return PermGroup(n, gens, known_order=known_order), s1


def even_subgroup_gens(gens: Sequence[Perm], n: int) -> List[Perm]:
    """Generators of <gens> intersected with Alt_n (index <= 2)."""
    from .perm import parity
    odd = [g for g in gens if parity(g) == 1]
    even = [g for g in gens if parity(g) == 0]
    if not odd:
        return list(even)
    h0 = odd[0]
    out = list(even)
    h0inv = inv(h0)
    for g in even:
        out.append(mul(mul(h0, g), h0inv))
    for g in odd:
        out.append(mul(g, h0inv))
        out.append(mul(h0, g))
    seen = set()
    res = []
    for g in out:
        if g not in seen and not is_identity(g):
            seen.add(g)
            res.append(g)
    return res
